function CommandEmpty({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.Empty>) {
  return (
    // cmdk announces results through aria-activedescendant on the input, and a
    // zero-result filter has no active descendant — so the move from "17
    // commands" to "no matches" is otherwise silent (4.1.3).
    <CommandPrimitive.Empty
      data-slot="command-empty"
      role="status"
      className={cn("py-6 text-center text-sm", className)}
      {...props}
    />
  )
}

